/// Centralized sizes for icons, buttons, cards, and other UI component dimensions.
abstract final class AppSizes {
  // --- Icon Sizes ---

  /// Extra small icons: 16.0
  static const double iconXs = 16.0;

  /// Small icons: 20.0
  static const double iconSm = 20.0;

  /// Medium icons: 24.0 (Default size for most Material actions)
  static const double iconMd = 24.0;

  /// Large icons: 32.0
  static const double iconLg = 32.0;

  /// Extra large icons: 40.0
  static const double iconXl = 40.0;

  // --- Button & Input Heights ---

  /// Height for small buttons: 32.0
  static const double buttonHeightSm = 32.0;

  /// Height for standard buttons: 48.0
  static const double buttonHeightMd = 48.0;

  /// Height for large buttons/inputs: 56.0
  static const double buttonHeightLg = 56.0;

  // --- Floating Action Button Sizes ---

  /// Default size for standard FAB: 56.0
  static const double fabSizeDefault = 56.0;

  /// Default size for small FAB: 40.0
  static const double fabSizeSmall = 40.0;

  /// Default size for large FAB: 96.0
  static const double fabSizeLarge = 96.0;
}
